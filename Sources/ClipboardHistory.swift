import SwiftUI

struct ClipboardItem: Identifiable {
    enum Content {
        case text(String)
        case image(NSImage)
    }

    let id = UUID()
    let content: Content
    let sourceApp: String?
    let date: Date

    var text: String? {
        if case .text(let text) = content { return text }
        return nil
    }
}

/// Remembers recent clipboard contents. There's no change notification for the pasteboard,
/// so this polls its change count. History lives in memory only and is gone when Icicle quits.
final class ClipboardHistory: ObservableObject {
    static let shared = ClipboardHistory()
    static let capacity = 50

    @Published private(set) var items: [ClipboardItem] = []

    private var timer: Timer?
    private var lastChangeCount = NSPasteboard.general.changeCount

    /// Markers password managers and similar apps put on copies that shouldn't be kept (nspasteboard.org).
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
    ]

    func setEnabled(_ enabled: Bool) {
        if enabled, timer == nil {
            lastChangeCount = NSPasteboard.general.changeCount
            timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
        } else if !enabled {
            timer?.invalidate()
            timer = nil
            items.removeAll()
        }
    }

    func clear() { items.removeAll() }

    func remove(_ item: ClipboardItem) { items.removeAll { $0.id == item.id } }

    /// Puts the item back on the clipboard and, with Accessibility access, pastes it into the frontmost app.
    func paste(_ item: ClipboardItem, autoPaste: Bool) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        switch item.content {
        case .text(let text): pasteboard.setString(text, forType: .string)
        case .image(let image): pasteboard.writeObjects([image])
        }
        lastChangeCount = pasteboard.changeCount
        items.removeAll { $0.id == item.id }
        items.insert(ClipboardItem(content: item.content, sourceApp: item.sourceApp, date: Date()), at: 0)

        guard autoPaste, AccessibilityAccess.isTrusted else { return }
        // Give the previous app a moment to take keyboard focus back from the picker.
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.08) { KeySynth.press(kVK_ANSI_V, flags: .maskCommand) }
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        let types = Set(pasteboard.types?.map(\.rawValue) ?? [])
        guard types.isDisjoint(with: Self.ignoredTypes) else { return }
        let source = NSWorkspace.shared.frontmostApplication?.localizedName

        if let text = pasteboard.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            items.removeAll { $0.text == text }
            add(ClipboardItem(content: .text(text), sourceApp: source, date: Date()))
        } else if let image = NSImage(pasteboard: pasteboard), image.isValid {
            add(ClipboardItem(content: .image(image), sourceApp: source, date: Date()))
        }
    }

    private func add(_ item: ClipboardItem) {
        items.insert(item, at: 0)
        if items.count > Self.capacity { items.removeLast(items.count - Self.capacity) }
    }
}

enum KeySynth {
    /// Posts a key press as if typed. Needs Accessibility access.
    static func press(_ keyCode: Int, flags: CGEventFlags) {
        let source = CGEventSource(stateID: .combinedSessionState)
        for down in [true, false] {
            let event = CGEvent(keyboardEventSource: source, virtualKey: CGKeyCode(keyCode), keyDown: down)
            event?.flags = flags
            event?.post(tap: .cghidEventTap)
        }
    }
}

// MARK: - Picker

/// A Spotlight-style panel that takes keyboard input without activating Icicle,
/// so the app you were typing in stays frontmost and receives the paste.
final class KeyablePanel: NSPanel {
    var onResignKey: (() -> Void)?

    init(size: NSSize) {
        super.init(contentRect: NSRect(origin: .zero, size: size),
                   styleMask: [.borderless, .nonactivatingPanel], backing: .buffered, defer: true)
        isOpaque = false
        backgroundColor = .clear
        hasShadow = true
        level = .popUpMenu
        isReleasedWhenClosed = false
        hidesOnDeactivate = false
        collectionBehavior = [.canJoinAllSpaces, .fullScreenAuxiliary, .transient, .ignoresCycle]
    }

    override var canBecomeKey: Bool { true }

    override func resignKey() {
        super.resignKey()
        onResignKey?()
    }

    func setContent<V: View>(_ view: V, cornerRadius: CGFloat = 16) {
        let effect = NSVisualEffectView()
        effect.material = .popover
        effect.blendingMode = .behindWindow
        effect.state = .active
        effect.wantsLayer = true
        effect.layer?.cornerRadius = cornerRadius
        effect.layer?.masksToBounds = true
        let host = NSHostingView(rootView: view)
        host.frame = effect.bounds
        host.autoresizingMask = [.width, .height]
        effect.addSubview(host)
        contentView = effect
    }

    /// Centers the panel in the upper part of the screen under the mouse.
    func present() {
        let mouse = NSEvent.mouseLocation
        let screen = NSScreen.screens.first { $0.frame.contains(mouse) } ?? NSScreen.main
        if let area = screen?.visibleFrame {
            setFrameOrigin(NSPoint(x: area.midX - frame.width / 2, y: area.minY + area.height * 0.62 - frame.height / 2))
        }
        makeKeyAndOrderFront(nil)
    }
}

final class ClipboardPickerModel: ObservableObject {
    @Published var query = "" { didSet { selection = 0 } }
    @Published var selection = 0

    let history: ClipboardHistory

    init(history: ClipboardHistory) { self.history = history }

    var results: [ClipboardItem] {
        guard !query.isEmpty else { return history.items }
        return history.items.filter { $0.text?.localizedCaseInsensitiveContains(query) ?? false }
    }
}

final class ClipboardPicker {
    private let settings = AppSettings.shared
    private let model = ClipboardPickerModel(history: .shared)
    private lazy var panel: KeyablePanel = {
        let panel = KeyablePanel(size: NSSize(width: 460, height: 460))
        panel.setContent(ClipboardPickerView(model: model, choose: { [weak self] in self?.choose($0) }))
        panel.onResignKey = { [weak self] in self?.close() }
        return panel
    }()
    private var keyMonitor: Any?

    func toggle() {
        panel.isVisible ? close() : open()
    }

    private func open() {
        model.query = ""
        model.selection = 0
        panel.present()
        keyMonitor = NSEvent.addLocalMonitorForEvents(matching: .keyDown) { [weak self] event in
            self?.handle(event) == true ? nil : event
        }
    }

    private func close() {
        if let keyMonitor { NSEvent.removeMonitor(keyMonitor) }
        keyMonitor = nil
        panel.orderOut(nil)
    }

    private func choose(_ item: ClipboardItem) {
        close()
        ClipboardHistory.shared.paste(item, autoPaste: settings.clipboardAutoPaste)
    }

    /// Arrow keys, Return, Esc and ⌘1–9; everything else goes to the search field.
    private func handle(_ event: NSEvent) -> Bool {
        let results = model.results
        switch Int(event.keyCode) {
        case kVK_Escape:
            close()
        case kVK_DownArrow:
            model.selection = min(model.selection + 1, max(results.count - 1, 0))
        case kVK_UpArrow:
            model.selection = max(model.selection - 1, 0)
        case kVK_Return, kVK_ANSI_KeypadEnter:
            if results.indices.contains(model.selection) { choose(results[model.selection]) }
        default:
            if event.modifierFlags.contains(.command), let digit = Int(event.charactersIgnoringModifiers ?? ""),
               (1...9).contains(digit), results.indices.contains(digit - 1) {
                choose(results[digit - 1])
                return true
            }
            return false
        }
        return true
    }
}

private struct ClipboardPickerView: View {
    @ObservedObject var model: ClipboardPickerModel
    @ObservedObject var history: ClipboardHistory
    let choose: (ClipboardItem) -> Void
    @FocusState private var searchFocused: Bool

    init(model: ClipboardPickerModel, choose: @escaping (ClipboardItem) -> Void) {
        self.model = model
        self.history = model.history
        self.choose = choose
    }

    var body: some View {
        let results = model.results
        VStack(spacing: 0) {
            HStack(spacing: 8) {
                Image(systemName: "magnifyingglass").foregroundStyle(.secondary)
                TextField("Search clipboard history", text: $model.query)
                    .textFieldStyle(.plain)
                    .font(.system(size: 16))
                    .focused($searchFocused)
            }
            .padding(14)

            Divider()

            if results.isEmpty {
                VStack(spacing: 8) {
                    Image(systemName: "doc.on.clipboard").font(.system(size: 30)).foregroundStyle(.tertiary)
                    Text(history.items.isEmpty ? "Copy something and it will show up here." : "No matches.")
                        .foregroundStyle(.secondary)
                }
                .frame(maxWidth: .infinity, maxHeight: .infinity)
            } else {
                ScrollViewReader { proxy in
                    ScrollView {
                        LazyVStack(spacing: 2) {
                            ForEach(Array(results.enumerated()), id: \.element.id) { index, item in
                                ClipboardRow(item: item, index: index, isSelected: index == model.selection)
                                    .id(item.id)
                                    .onTapGesture { choose(item) }
                            }
                        }
                        .padding(6)
                    }
                    .onChange(of: model.selection) { _, selection in
                        if results.indices.contains(selection) { proxy.scrollTo(results[selection].id) }
                    }
                }
            }

            Divider()
            HStack(spacing: 14) {
                Label("Paste", systemImage: "return")
                Label("Choose", systemImage: "arrow.up.arrow.down")
                Text("⌘1–9 Quick pick")
                Spacer()
                Text("esc")
            }
            .font(.caption)
            .foregroundStyle(.secondary)
            .padding(.horizontal, 14)
            .padding(.vertical, 8)
        }
        .onAppear { searchFocused = true }
    }
}

private struct ClipboardRow: View {
    let item: ClipboardItem
    let index: Int
    let isSelected: Bool

    var body: some View {
        HStack(spacing: 10) {
            Group {
                switch item.content {
                case .text:
                    Image(systemName: "text.alignleft").foregroundStyle(isSelected ? .white : .secondary)
                case .image(let image):
                    Image(nsImage: image).resizable().aspectRatio(contentMode: .fill)
                        .clipShape(RoundedRectangle(cornerRadius: 4))
                }
            }
            .frame(width: 28, height: 28)

            VStack(alignment: .leading, spacing: 2) {
                Text(title).lineLimit(2).font(.system(size: 13))
                Text(subtitle).font(.caption).foregroundStyle(isSelected ? .white.opacity(0.8) : .secondary).lineLimit(1)
            }
            Spacer(minLength: 0)
            if index < 9 {
                Text("⌘\(index + 1)").font(.caption.monospacedDigit())
                    .foregroundStyle(isSelected ? .white.opacity(0.8) : .secondary)
            }
        }
        .foregroundStyle(isSelected ? .white : .primary)
        .padding(.horizontal, 10)
        .padding(.vertical, 6)
        .background(RoundedRectangle(cornerRadius: 8, style: .continuous).fill(isSelected ? Color.snapHighlight : .clear))
        .contentShape(Rectangle())
    }

    private var title: String {
        switch item.content {
        case .text(let text): return text.trimmingCharacters(in: .whitespacesAndNewlines)
        case .image(let image): return "Image, \(Int(image.size.width)) × \(Int(image.size.height))"
        }
    }

    private var subtitle: String {
        let when = RelativeDateTimeFormatter().localizedString(for: item.date, relativeTo: Date())
        return [item.sourceApp, when].compactMap { $0 }.joined(separator: " · ")
    }
}
